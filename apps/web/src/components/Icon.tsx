export function Icon({
  name,
  className,
}: {
  name: string;
  className?: string;
}) {
  const Component = Object.hasOwn(icons, name)
    ? icons[name as IconName]
    : FileTextOutlined;
  return <Component className={className} aria-hidden="true" />;
}
